// A class's vtable, found by its RTTI name (the walk goblin::anchors::vtable_of runs).
//
// MSVC leaves a handle no patch moves: one qword BEFORE a vtable sits a pointer to the class's
// _RTTICompleteObjectLocator, and the locator names the class through its TypeDescriptor.
// Walking that backwards - name -> TypeDescriptor -> locator -> vtable - finds the class
// wherever the linker put it this time. The acceptance rules are the ones this walk has always
// had: exactly one place holds the name, and exactly one .rdata qword points at a locator of
// that TypeDescriptor. Anything else answers 0.
//
// What changed on 2026-09-23 is the cost. The first lookup of each name used to walk every
// section byte by byte - the whole 99 MB image for the name, .rdata again for the locator and
// again for the vtable - 65-90 ms PER NAME, and two of those ran on the game's UI thread the
// first time the settings screen opened over the map: one 186 ms frame. Now:
//   - The name is looked for only in writable, non-executable sections. A TypeDescriptor is a
//     writable object (its spare field caches the undecorated name at run time), so it is never
//     emitted into code or read-only data. On every build we hold (2.2.0 .. 2.7.1) all 12035
//     decorated class names sit in .data and nowhere else, so skipping the rest (.text, .rdata
//     and the small ones: 85 of the 99 MB) changes no answer - scratch/rtti_prewarm/ has the
//     census and the old-against-new comparison.
//   - memchr finds the name's first-byte candidates, and the two .rdata walks skip, 16 offsets
//     at a time, every offset that cannot hold a wanted value (each_candidate), instead of a
//     compare at every byte. Every offset that COULD still gets the exact compare, unaligned
//     ones included, so the matches are the same set the byte-by-byte walk found.
//   - Any number of names share the same three walks (names, locators, vtables), so the whole
//     list costs about what one name does alone.
namespace goblin::rtti_resolve
{
    struct Section
    {
        uint32_t rva = 0;
        uint32_t len = 0;       // VirtualSize - what the loader mapped
        bool name_home = false; // writable and not executable: where a TypeDescriptor can live
        bool rdata = false;     // named ".rdata": where the locators and the vtables live
    };

    // The section table, read from the module's own headers by offset (no Windows types, so
    // the offline test runs this very function on its mapped copies).
    inline std::vector<Section> sections_of(uintptr_t base)
    {
        std::vector<Section> out;
        if (!base)
            return out;
        const auto *img = reinterpret_cast<const uint8_t *>(base);
        uint32_t e_lfanew = 0;
        std::memcpy(&e_lfanew, img + 0x3C, 4);
        const uint8_t *nt = img + e_lfanew;
        uint16_t nsec = 0, opt_size = 0;
        std::memcpy(&nsec, nt + 6, 2);      // FileHeader.NumberOfSections
        std::memcpy(&opt_size, nt + 20, 2); // FileHeader.SizeOfOptionalHeader
        const uint8_t *sh = nt + 24 + opt_size;
        out.reserve(nsec);
        for (uint16_t i = 0; i < nsec; ++i, sh += 40)
        {
            uint32_t vsize = 0, va = 0, ch = 0;
            std::memcpy(&vsize, sh + 8, 4);
            std::memcpy(&va, sh + 12, 4);
            std::memcpy(&ch, sh + 36, 4);
            Section s{};
            s.rva = va;
            s.len = vsize;
            s.name_home = (ch & 0x80000000u) && !(ch & 0x20000000u); // MEM_WRITE, not MEM_EXECUTE
            s.rdata = std::memcmp(sh, ".rdata", 7) == 0;               // the NUL too: exactly ".rdata"
            out.push_back(s);
        }
        return out;
    }

    // Per batch. A longer list is resolved in batches of kMaxNames. More valid locators in one
    // batch than kMaxLocators makes the names that overflowed answer 0 (fail closed); the
    // classes looked up here have one locator each, so neither limit is anywhere near.
    constexpr size_t kMaxNames = 64;
    constexpr size_t kMaxLocators = 256;

    // Up to this many keys, the .rdata walks filter with SSE2; above it, with the dword hash.
    constexpr size_t kVectorKeys = 8;

    inline uint16_t dword_hash(uint32_t k)
    {
        return uint16_t((k * 2654435761u) >> 16);
    }

    // Call fn(off) for every offset in [0, len - width] at which one of the keys MAY start;
    // fn makes the exact comparison. This only skips offsets that cannot hold a key, so the
    // set of matches is exactly what a compare at every byte finds - unaligned ones included.
    //   - A few keys (the list at init, or one name on its own): SSE2, 16 offsets per step,
    //     on bytes 1 and 2 of each key. Those are the informative ones: byte 0 of a
    //     TypeDescriptor RVA or a locator address is a multiple of 4, and the high bytes are
    //     the ones most of .rdata shares (every RVA there is 0x02xxxxxx..0x04xxxxxx, every
    //     pointer 0x00007FFxxxxxxxxx).
    //   - Many keys (the offline test's batches): a hash of the dword at each offset against a
    //     64K-bit table - a load, a multiply and a bit test for a position that holds no key.
    // width is the key size, 4 or 8 bytes.
    template <typename F>
    inline void each_candidate(const uint8_t *p, size_t len, size_t width, const uint64_t *keys,
                               size_t nk, F &&fn)
    {
        if (!nk || width < 4 || len < width)
            return;
        const size_t last = len - width; // the last offset a whole key fits at
        if (nk > kVectorKeys)
        {
            uint64_t bm[1024] = {};
            for (size_t j = 0; j < nk; ++j)
            {
                const uint16_t h = dword_hash(uint32_t(keys[j]));
                bm[h >> 6] |= uint64_t(1) << (h & 63);
            }
            for (size_t off = 0; off <= last; ++off)
            {
                uint32_t lo = 0;
                std::memcpy(&lo, p + off, 4);
                const uint16_t h = dword_hash(lo);
                if (bm[h >> 6] & (uint64_t(1) << (h & 63)))
                    fn(off);
            }
            return;
        }
        uint8_t b1[kVectorKeys] = {}, b2[kVectorKeys] = {};
        __m128i v1[kVectorKeys], v2[kVectorKeys];
        for (size_t j = 0; j < nk; ++j)
        {
            b1[j] = uint8_t(keys[j] >> 8);
            b2[j] = uint8_t(keys[j] >> 16);
            v1[j] = _mm_set1_epi8(char(b1[j]));
            v2[j] = _mm_set1_epi8(char(b2[j]));
        }
        size_t off = 0;
        // One step tests starts off..off+15 and reads p[off+1 .. off+17], so it needs
        // off + 18 <= len; a start past `last` is dropped, and the tail finishes byte by byte.
        for (; off + 18 <= len; off += 16)
        {
            const __m128i a = _mm_loadu_si128(reinterpret_cast<const __m128i *>(p + off + 1));
            const __m128i b = _mm_loadu_si128(reinterpret_cast<const __m128i *>(p + off + 2));
            __m128i m = _mm_setzero_si128();
            for (size_t j = 0; j < nk; ++j)
                m = _mm_or_si128(m, _mm_and_si128(_mm_cmpeq_epi8(a, v1[j]),
                                                  _mm_cmpeq_epi8(b, v2[j])));
            unsigned bits = unsigned(_mm_movemask_epi8(m));
            while (bits)
            {
                const size_t at = off + size_t(std::countr_zero(bits));
                if (at <= last)
                    fn(at);
                bits &= bits - 1;
            }
        }
        for (; off <= last; ++off)
            for (size_t j = 0; j < nk; ++j)
                if (p[off + 1] == b1[j] && p[off + 2] == b2[j])
                {
                    fn(off);
                    break;
                }
    }

    inline void find_vtables_batch(uintptr_t base, const Section *secs, size_t nsec,
                                   const char *const *names, size_t n, uint32_t *out)
    {
        size_t nlen[kMaxNames] = {};
        uint32_t td_rva[kMaxNames] = {};
        uint32_t td_hits[kMaxNames] = {};
        uint32_t vt_rva[kMaxNames] = {};
        uint32_t vt_hits[kMaxNames] = {};
        bool overflow[kMaxNames] = {};
        for (size_t i = 0; i < n; ++i)
        {
            out[i] = 0;
            // The NUL is part of the needle: it keeps a prefix of a longer name from matching.
            nlen[i] = names[i] && names[i][0] ? std::strlen(names[i]) + 1 : 0;
        }

        // 1. The name string -> the TypeDescriptor that owns it (the name sits at +0x10).
        //    One memchr walk per distinct first byte - every decorated name starts with '.'.
        bool walked[256] = {};
        for (size_t i = 0; i < n; ++i)
        {
            if (!nlen[i])
                continue;
            const uint8_t c = uint8_t(names[i][0]);
            if (walked[c])
                continue;
            walked[c] = true;
            for (size_t s = 0; s < nsec; ++s)
            {
                if (!secs[s].name_home)
                    continue;
                const auto *p = reinterpret_cast<const uint8_t *>(base + secs[s].rva);
                const size_t len = secs[s].len;
                size_t off = 0;
                while (off < len)
                {
                    const auto *f = static_cast<const uint8_t *>(std::memchr(p + off, c, len - off));
                    if (!f)
                        break;
                    off = size_t(f - p);
                    for (size_t j = 0; j < n; ++j)
                    {
                        if (!nlen[j] || uint8_t(names[j][0]) != c || nlen[j] > len - off ||
                            std::memcmp(f, names[j], nlen[j]) != 0)
                            continue;
                        const uint64_t rva = uint64_t(secs[s].rva) + off;
                        if (rva >= 0x10)
                        {
                            td_rva[j] = uint32_t(rva - 0x10);
                            ++td_hits[j];
                        }
                    }
                    ++off;
                }
            }
        }

        // 2. Every .rdata reference to a TypeDescriptor, keeping only the ones that really are
        //    its locator. The TypeDescriptor RVA appears TWICE per class: in the
        //    _RTTICompleteObjectLocator (pTypeDescriptor at +12) and in the
        //    _RTTIBaseClassDescriptor (pTypeDescriptor at +0); demanding a single reference is
        //    what once made every class answer "not found" on a live 2.7.0. The x64 locator
        //    identifies itself: signature 1 at +0, and pSelf at +20 holding its OWN rva.
        uint64_t keys[kMaxLocators > kMaxNames ? kMaxLocators : kMaxNames];
        size_t nk = 0;
        for (size_t i = 0; i < n; ++i)
            if (td_hits[i] == 1)
                keys[nk++] = td_rva[i];
        struct Locator
        {
            uint64_t va; // absolute, as the relocated pointer before a vtable holds it
            size_t name;
        };
        Locator loc[kMaxLocators];
        size_t nloc = 0;
        for (size_t s = 0; nk && s < nsec; ++s)
        {
            if (!secs[s].rdata)
                continue;
            const auto *p = reinterpret_cast<const uint8_t *>(base + secs[s].rva);
            const size_t len = secs[s].len;
            const uint32_t sec_rva = secs[s].rva;
            each_candidate(p, len, 4, keys, nk, [&](size_t off) {
                uint32_t k = 0;
                std::memcpy(&k, p + off, 4);
                for (size_t i = 0; i < n; ++i)
                {
                    if (td_hits[i] != 1 || td_rva[i] != k)
                        continue;
                    if (off < 12 || off - 12 + 24 > len)
                        continue; // a locator is 24 bytes; do not read past the section
                    const uint32_t col_rva = uint32_t(sec_rva + off - 12);
                    uint32_t sig = 0, self = 0;
                    std::memcpy(&sig, reinterpret_cast<const void *>(base + col_rva), 4);
                    std::memcpy(&self, reinterpret_cast<const void *>(base + col_rva + 20), 4);
                    if (sig != 1 || self != col_rva)
                        continue; // a base-class descriptor, not the locator
                    if (nloc == kMaxLocators)
                    {
                        overflow[i] = true;
                        continue;
                    }
                    loc[nloc++] = Locator{uint64_t(base) + col_rva, i};
                }
            });
        }

        // 3. The vtable is one qword after whatever points at a locator.
        for (size_t l = 0; l < nloc; ++l)
            keys[l] = loc[l].va;
        for (size_t s = 0; nloc && s < nsec; ++s)
        {
            if (!secs[s].rdata)
                continue;
            const auto *p = reinterpret_cast<const uint8_t *>(base + secs[s].rva);
            const uint32_t sec_rva = secs[s].rva;
            each_candidate(p, secs[s].len, 8, keys, nloc, [&](size_t off) {
                uint64_t k = 0;
                std::memcpy(&k, p + off, 8);
                for (size_t l = 0; l < nloc; ++l)
                    if (loc[l].va == k)
                    {
                        vt_rva[loc[l].name] = uint32_t(sec_rva + off + 8);
                        ++vt_hits[loc[l].name];
                    }
            });
        }

        for (size_t i = 0; i < n; ++i)
            out[i] = (td_hits[i] == 1 && !overflow[i] && vt_hits[i] == 1) ? vt_rva[i] : 0;
    }

    // out[i] = the RVA of names[i]'s vtable, 0 when it is absent or ambiguous. `base` is the
    // module as the loader mapped AND relocated it: a vtable's locator pointer is compared as
    // an absolute address. Pass the decorated names exactly as the exe spells them.
    inline void find_vtables(uintptr_t base, const Section *secs, size_t nsec,
                             const char *const *names, size_t n, uint32_t *out)
    {
        for (size_t first = 0; first < n; first += kMaxNames)
            find_vtables_batch(base, secs, nsec, names + first,
                               n - first < kMaxNames ? n - first : kMaxNames, out + first);
    }
}
